def test_uv_lock_is_an_item_per_package_with_git_commits_as_spans() -> None:
    output = read("lockfiles/uv.lock")
    planner, solver, numpy = items(output)
    assert value(numpy.name) == "numpy" and value(numpy.release) == DeclaredVersion("2.1.0")
    assert numpy.digest.state == "not_applicable"  # an archive hash is no checkpoint or image
    assert value(solver.commit) == GitCommit(MAKE.SHA_IK_SOLVER)
    assert isinstance(solver.commit, Known) and isinstance(solver.commit.provenance, Provenance)
    assert isinstance(solver.commit.provenance.evidence.locator[-1], Span)
    assert isinstance(planner.release, Unknown)  # the editable root locks no version
    assert codes(output) == ["software_identity_missing"]
    assert assertion(output) is AssertionKind.STATED


