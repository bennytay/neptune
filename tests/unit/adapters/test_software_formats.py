"""What the software adapter reads from each format, value by value (ADR 0040).

The fixtures are generated by ``tests/fixtures/software/make_software_fixtures.py``; the values
asserted here are the generator's constants, and ``software_oracle.check_citations`` (run on every
fixture by ``test_software_adapter.py``) proves each value is where it cites.
"""

import importlib.util
import sys
from pathlib import Path
from types import ModuleType
from typing import Any, Final

from neptune.adapters.harness import SourceOutput
from neptune.identity.hashing import content_id
from neptune.model.knowledge import Ambiguous, AssertionKind, Known, Unknown
from neptune.model.machine import SoftwareConfiguration, SoftwareItem
from neptune.model.provenance import ByteRange, JsonPointer, Provenance, Span
from neptune.model.versions import (
    BuildId,
    ContainerImageDigest,
    DeclaredVersion,
    FirmwareVersion,
    GitCommit,
    HashAlgorithm,
    ModelCheckpointHash,
    SemanticVersion,
)


def _load(name: str) -> ModuleType:
    path = Path(__file__).parents[2] / "fixtures" / "software" / f"{name}.py"
    spec = importlib.util.spec_from_file_location(name, path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


ORACLE: Final = _load("software_oracle")
MAKE: Final = _load("make_software_fixtures")


def read(relative: str, **config: Any) -> SourceOutput:
    output: SourceOutput = ORACLE.run(ORACLE.fixture(relative), **config)
    return output


def items(output: SourceOutput) -> list[SoftwareItem]:
    found: list[SoftwareItem] = ORACLE.items(output)
    return found


def codes(output: SourceOutput) -> list[str]:
    found: list[str] = ORACLE.codes(output)
    return found


def value(state: object) -> object:
    assert isinstance(state, Known), state
    return state.value


def record(output: SourceOutput) -> SoftwareConfiguration:
    (found,) = output.records()
    assert isinstance(found, SoftwareConfiguration)
    return found


def assertion(output: SourceOutput) -> AssertionKind:
    return record(output).provenance.assertion_kind


# --- Git ---------------------------------------------------------------------------------------


def test_a_detached_head_is_its_commit_observed() -> None:
    output = read("git/HEAD_detached")
    (item,) = items(output)
    assert value(item.commit) == GitCommit(MAKE.SHA_MAIN)
    assert item.name.state == item.release.state == item.build.state == "not_covered"
    assert item.digest.state == "not_applicable"
    assert assertion(output) is AssertionKind.OBSERVED
    assert codes(output) == []


def test_a_symbolic_ref_names_its_ref_for_binding_and_makes_no_record() -> None:
    output = read("git/HEAD")
    assert output.records() == ()
    (finding,) = output.findings()
    assert finding.code == "software.git_symbolic_ref"
    assert finding.details == {"target": "refs/heads/main"}
    assert finding.subject.locator == (ByteRange(5, len("refs/heads/main")),)  # type: ignore[union-attr]


def test_packed_refs_are_an_item_per_ref_with_tags_peeled() -> None:
    output = read("git/packed-refs")
    found = {value(item.name): value(item.commit) for item in items(output)}
    assert found == {
        "refs/heads/main": GitCommit(MAKE.SHA_MAIN),
        "refs/remotes/origin/dev": GitCommit(MAKE.SHA_DEV),
        "refs/tags/v1.4.2": GitCommit(MAKE.SHA_TAG_COMMIT),  # the ^ line, not the tag object
    }
    assert codes(output) == []


def test_a_tag_in_old_packed_refs_may_be_a_tag_object_so_its_commit_is_unknown() -> None:
    output = read("git/packed-refs_unpeeled")
    main, tag = items(output)
    assert value(main.commit) == GitCommit(MAKE.SHA_MAIN)
    assert isinstance(tag.commit, Unknown)
    assert codes(output) == ["git_unpeeled_tag"]  # the identity gap is explained, not doubled


def test_corrupt_packed_ref_lines_are_skipped_and_the_rest_read() -> None:
    output = read("git/packed-refs_corrupt")
    (item,) = items(output)
    assert value(item.name) == "refs/heads/main"
    assert codes(output) == ["malformed_entry", "malformed_entry"]


