# --- SBOMs and image indexes -------------------------------------------------------------------


def test_cyclonedx_components_keep_their_kinds() -> None:
    output = read("sbom/robot.cdx.json")
    stack, policy, nav, motor, eigen, blas, sidecar = items(output)
    assert value(stack.release) == DeclaredVersion("4.2.0")
    # SHA-256 is chosen over the SHA-512 listed first: it is what content ids are.
    assert value(policy.digest) == ModelCheckpointHash(HashAlgorithm.SHA256, MAKE.POLICY_SHA256)
    assert value(nav.digest) == ContainerImageDigest(f"sha256:{MAKE.NAV_DIGEST}")
    assert value(motor.release) == FirmwareVersion("0x010E")
    assert value(eigen.release) == DeclaredVersion("3.4.0")
    assert value(blas.name) == "eigen-blas" and isinstance(blas.release, Unknown)
    assert isinstance(sidecar.digest, Unknown) and eigen.digest.state == "not_applicable"
    assert codes(output) == ["software_identity_missing", "software_identity_missing"]


def test_spdx_packages_give_digests_firmware_and_no_assertion() -> None:
    output = read("sbom/robot.spdx.json")
    image, lidar, libyaml = items(output)
    assert value(image.digest) == ContainerImageDigest(MAKE.IMAGE_DIGEST)
    assert value(lidar.release) == FirmwareVersion("3.0.7")
    assert isinstance(libyaml.release, Unknown)  # NOASSERTION
    assert codes(output) == ["software_identity_missing"]


def test_an_oci_index_is_an_item_per_manifest_digest() -> None:
    output = read("sbom/index.json")
    arm64, amd64 = items(output)
    assert value(arm64.digest) == ContainerImageDigest(MAKE.IMAGE_DIGEST)
    assert value(arm64.name) == "amr-runtime"
    assert value(arm64.release) == DeclaredVersion("1.2.0")
    assert arm64.commit.state == "not_covered"  # image.revision is VCS-agnostic: in the bytes
    assert value(amd64.digest) == ContainerImageDigest(MAKE.IMAGE_DIGEST_AMD64)
    bad = read("sbom/index_bad_digest.json")
    assert isinstance(items(bad)[1].digest, Unknown)
    assert codes(bad) == ["invalid_value", "software_identity_missing"]
