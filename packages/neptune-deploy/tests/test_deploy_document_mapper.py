def test_the_commissioning_report_maps_inventories_tests_constraints_and_sign_off() -> None:
    base = _base("manipulator_cell")
    oracle = _Oracle("manipulator_cell", base)
    commissioning = _one(_mapped(base), "commissioning_baseline")
    assert commissioning.commissioned.value.ticks == _seconds("2026-02-20 16:30")
    assert commissioning.configuration.value.value == "cfg-c3-1.4"
    assert [i.name.value for i in commissioning.hardware.value] == [
        "Manipulator R1",
        "Controller R1",
        "Gripper",
    ]
    controller = commissioning.hardware.value[1]
    assert controller.model.value == "OmniCore C30"
    assert controller.identifiers.value[0].value.value == "SN-C30-552"
    assert controller.version.value == FirmwareVersion("7.8.1")
    assert [(i.name.value, i.version.value) for i in commissioning.software.value] == [
        ("Palletising application", DeclaredVersion("1.4.0")),
        ("Safety configuration", DeclaredVersion("2026.02-a")),
    ]
    assert [c.value.value for c in commissioning.calibrations.value] == ["CAL-C3-001", "CAL-C3-002"]
    assert [(t.name.value, t.result.value) for t in commissioning.tests.value] == [
        ("Safety-rated monitored stop", "PASS"),
        ("Light curtain response", "PASS 142 ms"),
        ("Palletising cycle, 50 pallets", "PASS"),
    ]
    assert commissioning.tests.value[2].performed.value.ticks == _seconds("2026-02-20 14:15")
    assert [c.value for c in commissioning.constraints.value] == [
        "Payload not above 35 kg",
        "Pallet gate closed during automatic mode",
    ]
    # Each statement cites its own list item.
    assert [oracle.text(c.provenance.evidence) for c in commissioning.constraints.value] == [
        c.value for c in commissioning.constraints.value
    ]
    assert commissioning.sign_off.decision.value == "Accepted"
    assert commissioning.sign_off.time.value.ticks == _seconds("2026-02-21 09:10")


def test_the_incident_report_keeps_free_text_as_cited_spans_and_reads_its_timeline() -> None:
    base = _base("warehouse_amr")
    oracle = _Oracle("warehouse_amr", base)
    incident = _one(_mapped(base), "incident_record")
    assert incident.severity.value == "Minor, no injury"
    assert incident.zone.value.value == "Z3"
    assert incident.location.value == "Aisle 14, rack face B"
    assert [a.value.value for a in incident.assets.value] == ["PAL-5521", "RACK-14B"]
    assert incident.related.value[0].value.value == "RA-AMR-0417"
    assert incident.occurred.value.ticks == _seconds("2026-04-02 14:07")
    assert [(e.time.value.ticks, e.text.value) for e in incident.timeline.value] == [
        (_seconds("2026-04-02 14:05"), "AMR-07 starts pallet pick in aisle 14"),
        (_seconds("2026-04-02 14:07"), "Fork contacts rack upright; protective stop"),
        (_seconds("2026-04-02 14:09"), "Fleet manager flags AMR-07 as blocked"),
        (_seconds("2026-04-02 14:31"), "Technician clears the aisle and resets"),
    ]
    blocks = {b.provenance.evidence: b.text.value for b in _of(base, "document_block")}
    description, root_cause = incident.description, incident.root_cause
    # Verbatim: the description is the compiler's two paragraphs, one LF apart, as one span.
    assert description.value == (
        "While lifting pallet PAL-5521 the left fork touched the rack upright and the\n"
        "mast stopped. The pallet stayed on the forks.\n"
        "No person was in the aisle. The aisle was closed for 24 minutes."
    )
    assert oracle.text(description.provenance.evidence) == description.value
    first = description.provenance.evidence
    assert any(
        ref.locator[0] == first.locator[0] and _starts(ref) == _starts(first) for ref in blocks
    )
    assert root_cause.value == (
        "The rack face was 40 mm further out than the site map. The pick position\n"
        "had not been refreshed after the rack was re-bolted on 2026-03-28."
    )
    assert blocks[_block_of(blocks, root_cause.provenance.evidence)] == root_cause.value


def _starts(evidence: EvidenceRef) -> int:
    span = evidence.locator[-1]
    assert isinstance(span, Span)
    return span.start


def _block_of(blocks: dict[EvidenceRef, str], evidence: EvidenceRef) -> EvidenceRef:
    (found,) = [ref for ref in blocks if ref == evidence]
    return found


def test_the_sop_becomes_a_maintenance_event_from_a_pdf_and_from_markdown() -> None:
    package = _mapped(_base("inspection_quadruped"))
    events = _of(package, "maintenance_event")
    by_wo = {e.identifiers.value[0].value.value: e for e in events}
    assert set(by_wo) == {"WO-QD-5521", "WO-QD-6107"}
    pdf, markdown = by_wo["WO-QD-5521"], by_wo["WO-QD-6107"]
    for event in (pdf, markdown):
        assert (
            event.actions.value[0].value == "Power the robot down and place it on the service stand"
        )
        assert len(event.actions.value) == 4
        assert event.related.value[0].value.value == "SOP-MP-031"
        assert isinstance(event.site, NotCovered)
    assert pdf.performed.value.ticks == _days("2026-05-08")
    assert markdown.performed.value.ticks == _days("2026-05-19")
    assert [p.part.value for p in pdf.parts.value] == ["Foot pad FL", "Retaining screw set"]
    assert pdf.parts.value[0].removed.value[0].value.value == "FP-0183"
    assert pdf.parts.value[0].installed.value[0].value.value == "FP-0291"
    assert [p.part.value for p in markdown.parts.value] == ["Foot pad RR"]
    assert markdown.diagnosis.value == "Foot pad cracked on leg RR"
    # Markdown cites byte-for-byte spans of the file itself: no page.
    assert all(
        not isinstance(s.provenance.evidence.locator[0], Page)
        for s in _states(markdown.actions.value)
    )


def test_a_procedure_is_not_an_event_so_an_sop_without_a_work_record_does_not_match() -> None:
    base = _base("inspection_quadruped")
    records = tuple(
        replace(r, text=Known("Work order name: x", r.text.provenance))
        if r.kind == "document_block"
        and isinstance(r.text, Known)
        and r.text.value.startswith("Work order:")
        else r
        for r in base.records
    )
    package = _mapped(replace(base, records=records))
    assert _of(package, "maintenance_event") == []
    assert len(_codes(package)["document_unmatched"]) == 2


# --- Matching is an observation --------------------------------------------------------------


def test_a_match_is_an_observation_that_cites_the_structure_it_saw() -> None:
    base = _base("warehouse_amr")
    oracle = _Oracle("warehouse_amr", base)
    package = _mapped(base)
    risk = _one(package, "risk_assessment")
    finding = next(
        f
        for f in _codes(package)["template_matched"]
        if f.details["template"] == "risk.amr_iso3691_4"
    )
    assert finding.severity == "info"
    assert finding.records == (risk.id,)
    assert finding.subject == risk.provenance.evidence
    assert isinstance(finding.subject.locator[0], ByteRange)
    assert finding.details["version"] == "2"
    assert finding.details["not_covered"] == ["configuration", "related"]
    seen = [oracle.text(ref) for ref in finding.related]
    assert seen == [
        "RA-3691-AMR",
        "2",
        "RA-AMR-0417",
        "Hazard analysis",
        "Hazard\tSeverity\tExposure\tAvoidance\tRisk reduction\tMitigation",
    ]


def test_a_field_the_template_does_not_cover_is_not_covered_never_blank() -> None:
    package = _mapped(_base("warehouse_amr"))
    incident = _one(package, "incident_record")
    assert isinstance(incident.configuration, NotCovered)
    risk = _one(package, "risk_assessment")
    assert isinstance(risk.configuration, NotCovered)
    # A label the template names but the document lacks is also not covered, with a finding.
    base = _base("warehouse_amr")
    records = tuple(
        replace(r, text=Known("Zones: Z3", r.text.provenance))
        if r.kind == "document_block" and isinstance(r.text, Known) and r.text.value == "Zone: Z3"
        else r
        for r in base.records
    )
    package = _mapped(replace(base, records=records))
    assert isinstance(_one(package, "incident_record").zone, NotCovered)
    (absent,) = _codes(package)["label_absent"]
    assert absent.details["reference"] == "Zone" and absent.severity == "info"
