"""The document mapper over packages the compiler wrote from small PDFs and Markdown (ADR 0003).

The packages under ``fixtures/documents/packages`` are ``neptune ingest`` output, regenerated by
``make_document_fixtures.py``; these tests read them and never run ingestion. Every citation is
resolved back to the page text the compiler extracted (the block spans of ADR 0038 §3), or for
Markdown to the file's own bytes, and compared with what the record states.
"""

from collections.abc import Iterator
from dataclasses import replace
from datetime import date, datetime
from pathlib import Path
from typing import Any

import pytest

from neptune.model.knowledge import (
    AssertionKind,
    Known,
    KnownAbsent,
    NotCovered,
    Unknown,
)
from neptune.model.provenance import ByteRange, EvidenceRef, Page, Span
from neptune.model.versions import DeclaredVersion, FirmwareVersion
from neptune.store.package import IngestPackage, read_files, read_package
from neptune_deploy.lifecycle import (
    DOCUMENT_MAPPER_ID,
    DocumentTemplate,
    TemplateRegistry,
    map_files,
)

FIXTURES = Path(__file__).parent / "fixtures" / "documents"
TEMPLATES = FIXTURES / "templates"
EPOCH = date(1970, 1, 1)


def _base(name: str) -> IngestPackage:
    return read_package(FIXTURES / "packages" / name)


def _templates() -> list[DocumentTemplate]:
    return list(TemplateRegistry.from_paths([TEMPLATES]).templates())


def _mapped(base: IngestPackage, templates: list[DocumentTemplate] | None = None) -> IngestPackage:
    return read_files(map_files(base, templates=templates or _templates()))


def _of(package: IngestPackage, kind: str) -> list[Any]:
    return [r for r in package.records if r.kind == kind]


def _codes(package: IngestPackage) -> dict[str, list[Any]]:
    out: dict[str, list[Any]] = {}
    for finding in _of(package, "ingest_finding"):
        assert finding.code.startswith(f"{DOCUMENT_MAPPER_ID}.")
        out.setdefault(finding.code.split(".")[-1], []).append(finding)
    return out


def _one(package: IngestPackage, kind: str) -> Any:
    (record,) = _of(package, kind)
    return record


def _raw(name: str, package: IngestPackage) -> dict[Any, bytes]:
    paths = {r.content_id: r.location.path for r in _of(package, "source_revision")}
    return {
        source: (FIXTURES / "sources" / name / path).read_bytes() for source, path in paths.items()
    }


class _Oracle:
    """What a citation points at: the compiler's page text for a PDF (each block's text then LF, in
    reading order: ADR 0038 §3), the file's own text for Markdown."""

    def __init__(self, name: str, base: IngestPackage) -> None:
        self.raw = _raw(name, base)
        self.pages: dict[tuple[Any, int | None], str] = {}
        by_page: dict[tuple[Any, int | None], list[Any]] = {}
        for block in sorted(_of(base, "document_block"), key=lambda b: b.order):
            evidence = block.provenance.evidence
            first = evidence.locator[0]
            page = first.index if isinstance(first, Page) else None
            by_page.setdefault((evidence.source, page), []).append(block)
        for key, blocks in by_page.items():
            if key[1] is not None:
                self.pages[key] = "".join(
                    (b.text.value if isinstance(b.text, Known) else "￼") + "\n" for b in blocks
                )

    def text(self, evidence: EvidenceRef) -> str:
        steps: list[Any] = list(evidence.locator)
        page = None
        if isinstance(steps[0], Page):
            page = steps.pop(0).index
        if page is None:
            text = self.raw[evidence.source].decode("utf-8")
        else:
            text = self.pages[(evidence.source, page)]
        for step in steps:
            assert isinstance(step, Span), step
            text = text[step.start : step.end]
        return text


def _states(value: Any) -> Iterator[Any]:
    """Every Knowledge state inside a record's fields; a Known list is structure, not a value."""
    if isinstance(value, Known) and isinstance(value.value, tuple):
        yield from _states(value.value)
    elif isinstance(value, Known | Unknown | KnownAbsent | NotCovered):
        yield value
    elif isinstance(value, tuple):
        for item in value:
            yield from _states(item)
    elif hasattr(value, "__dataclass_fields__") and not hasattr(value, "kind"):
        for name in value.__dataclass_fields__:
            yield from _states(getattr(value, name))


def _record_states(record: Any) -> Iterator[Any]:
    for name in record.__dataclass_fields__:
        if name not in ("id", "provenance"):
            yield from _states(getattr(record, name))


def _days(text: str, pattern: str = "%Y-%m-%d") -> int:
    return (datetime.strptime(text, pattern).date() - EPOCH).days


def _seconds(text: str) -> int:
    """Seconds from 1970-01-01T00:00:00 of the text's own civil clock, never moved to UTC."""
    return int((datetime.strptime(text, "%Y-%m-%d %H:%M") - datetime(1970, 1, 1)).total_seconds())


ARCHETYPES = {
    "warehouse_amr": {"risk_assessment": 1, "incident_record": 1},
    "manipulator_cell": {"risk_assessment": 1, "commissioning_baseline": 1},
    "inspection_quadruped": {"maintenance_event": 2},
}


@pytest.mark.parametrize("name", sorted(ARCHETYPES))
def test_each_archetype_maps_to_its_records_and_every_document_matches(name: str) -> None:
    package = _mapped(_base(name))
    for kind, count in ARCHETYPES[name].items():
        assert len(_of(package, kind)) == count, kind
    matched = _codes(package)["template_matched"]
    assert len(matched) == sum(ARCHETYPES[name].values())
    assert {f.severity for f in matched} == {"info"}


@pytest.mark.parametrize("name", sorted(ARCHETYPES))
def test_every_known_value_is_the_text_of_the_span_or_cell_it_cites(name: str) -> None:
    base = _base(name)
    oracle = _Oracle(name, base)
    package = _mapped(base)
    checked = 0
    for kind in ARCHETYPES[name]:
        for record in _of(package, kind):
            assert record.provenance.assertion_kind is AssertionKind.STATED
            for state in _record_states(record):
                if not isinstance(state, Known):
                    continue
                provenance: Any = state.provenance
                assert provenance.assertion_kind is AssertionKind.STATED
                cited = oracle.text(provenance.evidence)
                value = state.value
                if hasattr(value, "namespace"):
                    assert cited == value.value
                elif isinstance(value, str):
                    assert cited == value
                elif hasattr(value, "ticks"):
                    assert cited and cited[0].isdigit()
                else:
                    assert cited == value.value  # a declared version
                checked += 1
    assert checked > 20


def test_the_oracle_agrees_with_every_block_the_compiler_cut() -> None:
    for name in ARCHETYPES:
        base = _base(name)
        oracle = _Oracle(name, base)
        blocks = [b for b in _of(base, "document_block") if isinstance(b.text, Known)]
        assert blocks
        for block in blocks:
            assert oracle.text(block.provenance.evidence) == block.text.value


# --- Risk assessments: two formats -----------------------------------------------------------


def test_the_amr_risk_assessment_is_parsed_as_declared() -> None:
    package = _mapped(_base("warehouse_amr"))
    risk = _one(package, "risk_assessment")
    assert [i.value for i in risk.identifiers.value] == [_id("hh.risk_assessment", "RA-AMR-0417")]
    assert risk.site.value.value == "HH-DC2"
    assert [m.value.value for m in risk.machines.value] == ["AMR-07", "AMR-08"]
    assert risk.method.value == "ISO 3691-4 risk estimation (severity, exposure, avoidance)"
    assert risk.assessed.value.ticks == _days("2026-03-12")
    assert risk.approval.decision.value == "Accepted with conditions"
    assert risk.approval.authority.value == "Site safety lead"
    assert risk.approval.time.value.ticks == _days("2026-03-14")
    assert isinstance(risk.configuration, NotCovered) and isinstance(
        risk.related, NotCovered
    )  # no section lists them
    hazards = risk.hazards.value
    assert [h.hazard.value for h in hazards] == [
        "Collision with a pedestrian in a shared aisle",
        "Fork contact with a rack during pallet pick",
        "Battery thermal event while charging",
    ]
    for hazard in hazards:
        assert [s.name for s in hazard.scores.value] == [
            "Severity",
            "Exposure",
            "Avoidance",
            "Risk reduction",
        ]
    # Scores are the table's own text: never ranked, never converted.
    assert [[s.value.value for s in h.scores.value] for h in hazards] == [
        ["S3", "E2", "A2", "PLr d"],
        ["S2", "E2", "A1", "PLr c"],
        ["S3", "E1", "A2", "PLr c"],
    ]
    assert [m.value for m in hazards[0].mitigations.value] == [
        "Personnel-detecting scanner",
        "speed limited to 1.2 m/s in aisle zones",
    ]


def _id(namespace: str, value: str) -> Any:
    from neptune.model.ids import LogicalId

    return LogicalId(namespace, value)


def test_the_cell_risk_assessment_reads_a_headerless_table_and_its_own_column_names() -> None:
    package = _mapped(_base("manipulator_cell"))
    risk = _one(package, "risk_assessment")
    assert risk.identifiers.value[0].value.value == "CELL3-RA-009"
    assert risk.site.value.value == "Cell 3, Line 2"
    assert [m.value.value for m in risk.machines.value] == ["R1 6-axis", "R2 6-axis"]
    # Day-first, as the template declares: 12 March 2026, not 3 December.
    assert risk.assessed.value.ticks == _days("12/03/2026", "%d/%m/%Y")
    assert risk.approval.decision.value == "Approved"
    assert risk.approval.time.value.ticks == _days("14/03/2026", "%d/%m/%Y")
    names = [[s.name for s in h.scores.value] for h in risk.hazards.value]
    assert names == [["Severity of injury", "Exposure", "Avoidance", "Risk level"]] * 3
    assert [s.value.value for s in risk.hazards.value[1].scores.value] == [
        "Serious",
        "Seldom",
        "Possible",
        "Medium",
    ]
    assert [m.value for m in risk.hazards.value[2].mitigations.value] == [
        "Reduced speed 250 mm/s",
        "enabling switch",
    ]


def test_a_column_no_field_reads_and_a_row_nobody_read_are_findings_not_silence() -> None:
    package = _mapped(_base("manipulator_cell"))
    codes = _codes(package)
    (column,) = codes["column_unmapped"]
    assert column.details["columns"] == ["Task"] and column.severity == "warning"
    unread = [f for f in codes["text_unread"] if f.details["template"] == "risk.robot_cell"]
    (finding,) = unread
    assert finding.details["count"] == 1
    oracle = _Oracle("manipulator_cell", _base("manipulator_cell"))
    assert [oracle.text(ref) for ref in finding.related] == ["Revision\tB"]


def test_the_two_risk_formats_make_the_same_kind_from_different_structure() -> None:
    amr = _one(_mapped(_base("warehouse_amr")), "risk_assessment")
    cell = _one(_mapped(_base("manipulator_cell")), "risk_assessment")
    assert type(amr) is type(cell)
    assert [s.name for s in amr.hazards.value[0].scores.value] != [
        s.name for s in cell.hazards.value[0].scores.value
    ]


