def test_malformed_rows_are_findings_never_dropped_or_merged() -> None:
    package = _mapped("warehouse_amr")
    codes = _codes(package)
    # Duplicated work-order ids: both records kept, one finding naming the second.
    twins = _by_id(package, "maintenance_event", "cmms.work_order", "WO-26-0313")
    assert len(twins) == 2
    (repeated,) = codes["identifier_repeated"]
    assert repeated.records[0] in {t.id for t in twins}
    # A missing completion date is Unknown citing its cell, and the column is required.
    missing = next(t for t in twins if t.machines[0].value.value == "AMR-09")
    assert isinstance(missing.performed, Unknown)
    assert _place(missing.performed) == (RowCell(4, 4, "Completed"),)
    assert codes["value_blank"][0].details["rows"] == [4]
    # A date in another format than declared is not guessed.
    (late,) = _by_id(package, "maintenance_event", "cmms.work_order", "WO-26-0315")
    assert isinstance(late.performed, Unknown)
    assert codes["value_unreadable"][0].details["rows"] == [6]
    # A work order type the mapping does not name, and a column it does not map.
    rows = sorted(r for f in codes["row_unmatched"] for r in f.details["rows"])
    assert rows == [2, 5]  # the Jira task (array index 2) and the INSP work order (row 5)
    columns = sorted(c for f in codes["column_unmapped"] for c in f.details["columns"])
    assert columns == ["/fields/customfield_10040", "Downtime h"]


