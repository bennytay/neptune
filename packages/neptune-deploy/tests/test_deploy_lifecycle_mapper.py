# --- Lineage and determinism ---------------------------------------------------------------------


def test_transform_names_mapper_mapping_hash_and_base_package() -> None:
    base = _base("warehouse_amr")
    mapping = preset("cmms_generic")
    package = read_files(map_files(base, [mapping]))
    transforms = {t.id: t for t in _of(package, "transform_record")}
    (mapper,) = [t for t in transforms.values() if t.config.get("mapping_sha256")]
    assert (mapper.adapter_id, mapper.adapter_version) == (MAPPER_ID, MAPPER_VERSION)
    assert mapper.config["base_package"] == base.id
    assert mapper.config["mapping_sha256"] == mapping.sha256
    (upstream,) = mapper.upstream
    assert transforms[upstream].adapter_id == "tabular"
    # The tables no mapping applies to are findings of a run transform, not silence.
    unmapped = _codes(package)["table_unmapped"]
    assert len(unmapped) == 2


def test_same_inputs_give_byte_identical_packages_in_any_order() -> None:
    base = _base("manipulator_cell")
    mappings = _mappings("manipulator_cell")
    first = map_files(base, mappings)
    assert map_files(base, list(reversed(mappings))) == first
    assert map_files(_base("manipulator_cell"), mappings) == first


def test_a_changed_mapping_is_new_lineage() -> None:
    base = _base("warehouse_amr")
    original = preset("cmms_generic")
    document = dict(original.document)
    document["version"] = "2"
    changed = parse_mapping(json.dumps(document).encode())
    old = {r.id for r in _of(read_files(map_files(base, [original])), "maintenance_event")}
    new = {r.id for r in _of(read_files(map_files(base, [changed])), "maintenance_event")}
    assert old and new and not old & new


def _tree(root: Path) -> dict[str, str]:
    return {
        str(p.relative_to(root)): hashlib.sha256(p.read_bytes()).hexdigest()
        for p in sorted(root.rglob("*"))
        if p.is_file()
    }


def test_map_package_writes_a_readable_package_and_leaves_the_base_untouched(
    tmp_path: Path,
) -> None:
    root = FIXTURES / "packages" / "warehouse_amr"
    before = _tree(root)
    package_id = map_package(root, [preset("cmms_generic")], tmp_path / "out")
    assert _tree(root) == before
    written = read_package(tmp_path / "out")
    assert written.id == package_id
    assert written.manifest.version == 3


