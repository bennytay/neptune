def _rule_mapping(rules: list[dict[str, Any]]) -> LifecycleMapping:
    return parse_mapping(
        json.dumps(
            {
                "schema": "neptune-deploy.lifecycle-mapping/1",
                "id": "test.rules",
                "version": "1",
                "zone": "unstated",
                "rules": rules,
            }
        ).encode()
    )


def test_a_row_two_rules_match_gets_no_record() -> None:
    rule = {
        "kind": "maintenance_event",
        "requires": ["WO Number"],
        "fields": {"identifiers": [{"column": "WO Number", "namespace": "wo"}]},
    }
    mapping = _rule_mapping([{**rule, "id": "a"}, {**rule, "id": "b"}])
    package = read_files(map_files(_base("warehouse_amr"), [mapping]))
    assert _of(package, "maintenance_event") == []
    (ambiguous,) = _codes(package)["rule_ambiguous"]
    assert ambiguous.details["count"] == 6
    assert ambiguous.severity == "error"


def test_a_table_with_an_undeclared_header_is_a_finding() -> None:
    base = _base("inspection_quadruped")
    records = [
        replace(r, header=Unknown(r.header.provenance)) if r.kind == "structured_table" else r
        for r in base.records
    ]
    unheaded = read_files(package_files(records))
    package = read_files(map_files(unheaded, [preset("cmms_maximo")]))
    assert _of(package, "maintenance_event") == []
    assert len(_codes(package)["header_undeclared"]) == 1


def test_a_table_declared_headerless_is_unmapped_not_undeclared() -> None:
    base = _base("inspection_quadruped")
    records = [
        replace(r, header=NotApplicable()) if r.kind == "structured_table" else r
        for r in base.records
    ]
    package = read_files(map_files(read_files(package_files(records)), [preset("cmms_maximo")]))
    codes = _codes(package)
    assert "header_undeclared" not in codes
    assert len(codes["table_unmapped"]) == 1


def test_a_mapped_column_the_table_lacks_is_not_covered() -> None:
    mapping = _rule_mapping(
        [
            {
                "id": "wo",
                "kind": "maintenance_event",
                "requires": ["WONUM"],
                "fields": {"diagnosis": {"column": "Problem statement"}},
            }
        ]
    )
    package = read_files(map_files(_base("inspection_quadruped"), [mapping]))
    events = _of(package, "maintenance_event")
    assert len(events) == 2
    assert all(type(e.diagnosis).__name__ == "NotCovered" for e in events)
    (absent,) = _codes(package)["column_absent"]
    assert absent.details["column"] == "Problem statement"
    assert absent.details["count"] == 1  # one column, however many rows read it


