FIXTURES = Path(__file__).parent / "fixtures" / "lifecycle"
REQUALIFICATION = FIXTURES / "mappings" / "cell3_requalification.json"
ARCHETYPES: dict[str, tuple[str, ...]] = {
    "warehouse_amr": ("cmms_generic", "jira_json", "register_zone"),
    "manipulator_cell": ("servicenow_csv", "linear_csv", "register_risk", "register_asset"),
    "inspection_quadruped": ("cmms_maximo",),
}


def _base(name: str) -> IngestPackage:
    return read_package(FIXTURES / "packages" / name)


def _mappings(name: str) -> list[LifecycleMapping]:
    mappings = [preset(p) for p in ARCHETYPES[name]]
    if name == "manipulator_cell":
        mappings.append(load_mapping(REQUALIFICATION))
    return mappings


def _mapped(name: str) -> IngestPackage:
    return read_files(map_files(_base(name), _mappings(name)))


def _of(package: IngestPackage, kind: str) -> list[Any]:
    return [r for r in package.records if r.kind == kind]


def _codes(package: IngestPackage) -> dict[str, list[Any]]:
    out: dict[str, list[Any]] = {}
    for finding in _of(package, "ingest_finding"):
        out.setdefault(finding.code.split(".")[-1], []).append(finding)
    return out


def _place(state: Any) -> tuple[Any, ...]:
    """The locator a state's own provenance cites."""
    assert isinstance(state.provenance, Provenance)
    return state.provenance.evidence.locator


def _by_id(package: IngestPackage, kind: str, namespace: str, value: str) -> list[Any]:
    return [
        r
        for r in _of(package, kind)
        if any(
            isinstance(i, Known) and (i.value.namespace, i.value.value) == (namespace, value)
            for i in r.identifiers
        )
    ]


# --- Citations resolve to the exact source bytes -------------------------------------------------


def _raw(name: str, package: IngestPackage) -> dict[str, bytes]:
    paths = {r.content_id: r.location.path for r in _of(package, "source_revision")}
    return {source: (FIXTURES / name / path).read_bytes() for source, path in paths.items()}


def _resolve(raw: bytes, locator: tuple[Any, ...]) -> Any:
    """What a citation points at, read with the standard library."""
    first = locator[0]
    if isinstance(first, RowCell):
        rows = list(csv.reader(io.StringIO(raw.decode("utf-8", errors="replace"), newline="")))
        text = rows[first.row][first.column]
        assert first.column_name == rows[0][first.column]
        if len(locator) == 2:
            span = locator[1]
            assert isinstance(span, Span)
            return text[span.start : span.end]
        return text
    assert isinstance(first, ByteRange) and isinstance(locator[1], JsonPointer)
    value = json.loads(raw[first.offset : first.offset + first.length])
    for token in locator[1].pointer.split("/")[1:]:
        value = value[int(token)] if isinstance(value, list) else value[token]
    return value


def _states(value: Any) -> Iterator[Any]:
    """Every Knowledge state inside a record's fields."""
    if isinstance(value, Known | Unknown | KnownAbsent):
        yield value
    elif isinstance(value, tuple):
        for item in value:
            yield from _states(item)
    elif hasattr(value, "__dataclass_fields__") and not hasattr(value, "kind"):
        for name in value.__dataclass_fields__:
            yield from _states(getattr(value, name))


def _record_states(record: Any) -> Iterator[Any]:
    for name in record.__dataclass_fields__:
        if name not in ("id", "provenance"):
            yield from _states(getattr(record, name))


@pytest.mark.parametrize("name", sorted(ARCHETYPES))
def test_every_known_value_is_the_text_of_the_cell_it_cites(name: str) -> None:
    package = _mapped(name)
    raw = _raw(name, package)
    checked = 0
    for kind in LIFECYCLE_KINDS:
        for record in _of(package, kind.kind):
            assert record.provenance.assertion_kind is AssertionKind.STATED
            for state in _record_states(record):
                if not isinstance(state, Known) or not isinstance(state.provenance, Provenance):
                    continue
                evidence = state.provenance.evidence
                assert state.provenance.assertion_kind is AssertionKind.STATED
                assert isinstance(evidence.source, str)
                cited = _resolve(raw[evidence.source], evidence.locator)
                value = state.value
                if hasattr(value, "namespace"):
                    value = value.value
                elif hasattr(value, "value") and isinstance(value.value, str):
                    value = value.value  # a version
                if isinstance(value, float):
                    assert float(cited) == value
                elif isinstance(value, str):
                    assert cited == value
                checked += 1
    assert checked > 10


# --- The warehouse AMR fleet --------------------------------------------------------------------


def test_amr_work_orders_keep_parts_serials_and_firmware_as_declared() -> None:
    package = _mapped("warehouse_amr")
    (event,) = _by_id(package, "maintenance_event", "cmms.work_order", "WO-26-0311")
    (part,) = event.parts
    assert part.part.value == "Drive wheel assembly"
    assert [i.value.value for i in part.removed] == ["DW-11873"]
    assert [i.value.value for i in part.installed] == ["DW-12990"]
    assert event.configuration.value.namespace == "firmware"
    assert event.configuration.value.value == "4.2.0"
    assert [a.value for a in event.actions] == ["Replace drive wheel", "Clean lidar window"]
    assert event.actions[1].provenance.evidence.locator[-1] == Span(21, 39)
    assert [m.value.value for m in event.machines] == ["AMR-07"]
    # A work order with no part swapped lists none, and says so.
    twins = _by_id(package, "maintenance_event", "cmms.work_order", "WO-26-0313")
    (flash,) = [t for t in twins if t.machines[0].value.value == "AMR-07"]
    assert flash.parts == ()
    assert "item_blank" in _codes(package)
    assert [r.value.value for r in flash.related] == ["CHG-0042", "INC-0007"]


def test_civil_times_keep_their_own_clock_and_record_the_declared_zone() -> None:
    package = _mapped("warehouse_amr")
    (event,) = _by_id(package, "maintenance_event", "cmms.work_order", "WO-26-0311")
    stamp = event.performed.value
    # 2026-03-02 09:40 on its own civil clock, never moved to UTC.
    assert stamp.ticks == 20514 * 86400 + 9 * 3600 + 40 * 60
    (domain,) = [d for d in _of(package, "timestamp_domain") if d.id == stamp.domain_id]
    assert domain.field == "Completed"
    assert domain.scope == ()  # the declared zone is the mapping's, never the clock's scope
    assert isinstance(domain.timescale, Unknown)
    assert domain.resolution == Known(Fraction(1))


def test_stated_offsets_are_instants_on_a_posix_clock() -> None:
    package = _mapped("warehouse_amr")
    (incident,) = _by_id(package, "incident_record", "jira.issue", "INC-0007")
    stamp = incident.occurred.value
    # 2026-03-01T13:42:10.000+0100 is 12:42:10Z, in milliseconds.
    assert stamp.ticks == (20513 * 86400 + 12 * 3600 + 42 * 60 + 10) * 1000
    (domain,) = [d for d in _of(package, "timestamp_domain") if d.id == stamp.domain_id]
    assert domain.timescale == Known(Timescale.POSIX)
    assert domain.scope == ()
    assert domain.resolution == Known(Fraction(1, 1000))
    assert incident.severity.value == "S2"
    assert incident.location.value == "Aisle 14, outbound dock"


def test_zone_register_splits_declared_lists_and_keeps_units() -> None:
    package = _mapped("warehouse_amr")
    (envelope,) = _by_id(package, "authorisation_envelope", "register.envelope", "ENV-S007-03")
    assert [m.value.value for m in envelope.machines] == ["AMR-07", "AMR-09", "AMR-12"]
